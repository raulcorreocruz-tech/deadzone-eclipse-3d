import {chromium} from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--no-sandbox']});
const reports=[];
try{
 const page=await browser.newPage({viewport:{width:915,height:412},deviceScaleFactor:2.5,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3000/',{waitUntil:'domcontentloaded',timeout:45000});
 await page.locator('#start').waitFor({timeout:35000});
 const menu=await page.evaluate(()=>window.__DZQA?.metrics());
 if(!menu)throw Error('instrumentation missing');
 if(menu.renderScale<1.1)throw Error('Auto resolution too low: '+menu.renderScale);
 await page.locator('#start').click();
 await page.locator('#dz44-pause').waitFor({state:'visible',timeout:8000});
 await page.waitForTimeout(600);
 let state=await page.evaluate(()=>window.__DZQA.metrics());
 if(state.renderScale<1.05||state.bufferWidth<state.cssWidth*1.05)throw Error('mobile remains blurry: '+JSON.stringify(state));
 await page.screenshot({path:'v44-mobile-game.png'});
 await page.locator('#dz44-pause').click();
 if(!await page.locator('#pauseModal').isVisible())throw Error('pause dialog not visible');
 const paused=await page.evaluate(()=>window.__DZQA.metrics());
 if(!paused.paused||paused.onlinePaused)throw Error('solo pause should freeze the game '+JSON.stringify(paused));
 await page.waitForTimeout(320);
 const frozen=await page.evaluate(()=>window.__DZQA.metrics());
 if(Math.abs(paused.gameTime-frozen.gameTime)>.001)throw Error('game time advances during solo pause');
 await page.screenshot({path:'v44-mobile-paused.png'});
 await page.locator('#resume').click();
 const resumed=await page.evaluate(()=>window.__DZQA.metrics());
 if(resumed.paused)throw Error('resume did not work');
 await page.evaluate(()=>window.__DZQA.setQuality('high'));
 const high=await page.evaluate(()=>window.__DZQA.metrics());
 if(high.renderScale<1.5||high.bufferWidth<high.cssWidth*1.5)throw Error('high quality still blurred '+JSON.stringify(high));
 await page.evaluate(()=>window.__DZQA.setQuality('low'));
 const low=await page.evaluate(()=>window.__DZQA.metrics());
 if(low.renderScale>.85)throw Error('performance option lost '+JSON.stringify(low));
 await page.evaluate(()=>window.__DZQA.setQuality('auto'));
 await page.evaluate(()=>window.__DZQA.setCoop(true));
 await page.locator('#dz44-pause').click();
 const coop=await page.evaluate(()=>window.__DZQA.metrics());
 if(coop.paused||!coop.onlinePaused)throw Error('coop pause incorrectly stops global simulation '+JSON.stringify(coop));
 if(!await page.locator('#pauseInfo').innerText().then(x=>x.includes('sigue avanzando')))throw Error('coop warning missing');
 await page.locator('#resume').click();
 await page.evaluate(()=>window.__DZQA.setCoop(false));
 if(errors.length)throw Error('Runtime errors '+errors.join(' / ').slice(0,800));
 reports.push({platform:'Android landscape simulated',auto:menu.renderScale,high:high.renderScale,low:low.renderScale,pauseSolo:true,resume:true,coopSafe:true,errors});
 await page.close();
}finally{await browser.close()}
fs.writeFileSync('mobile-v44-results.json',JSON.stringify({status:'passed',reports},null,2));
console.log('MOBILE V44 PASS',JSON.stringify(reports));
